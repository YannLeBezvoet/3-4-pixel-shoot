// The behavior reference (docs/reference/behaviors.md), generated from the engine's behavior
// registry: what each behavior does and the parameters a theme gives it.
import type { BehaviorKind, BehaviorRegistry } from '@pixel-shoot/sim';
import { z } from 'zod';

interface JsonSchema {
  type?: string;
  enum?: unknown[];
  anyOf?: JsonSchema[];
  minimum?: number;
  maximum?: number;
  exclusiveMinimum?: number;
  exclusiveMaximum?: number;
  default?: unknown;
  description?: string;
  properties?: Record<string, JsonSchema>;
  required?: string[];
}

const SECTIONS: { kind: BehaviorKind; title: string; file: string }[] = [
  { kind: 'weapon', title: 'Weapon behaviors', file: 'weapons.json' },
  { kind: 'projectile', title: 'Projectile behaviors', file: 'projectiles.json' },
  { kind: 'map-element', title: 'Map-element behaviors', file: 'maps (Tiled)' },
];

/** Zod adds the safe-integer limits to every integer; they mean "no limit" here. */
const isLimit = (value: number | undefined) =>
  value !== undefined && Math.abs(value) < Number.MAX_SAFE_INTEGER;

function typeOf(schema: JsonSchema): string {
  if (schema.anyOf) return schema.anyOf.map(typeOf).join(' or ');
  if (schema.enum) return schema.enum.map((v) => `\`${JSON.stringify(v)}\``).join(', ');
  const name =
    schema.type === 'integer' ? 'whole number' : schema.type === 'null' ? '`null`' : (schema.type ?? 'any');
  const bounds: string[] = [];
  if (isLimit(schema.exclusiveMinimum)) bounds.push(`> ${schema.exclusiveMinimum}`);
  if (isLimit(schema.minimum)) bounds.push(`≥ ${schema.minimum}`);
  if (isLimit(schema.exclusiveMaximum)) bounds.push(`< ${schema.exclusiveMaximum}`);
  if (isLimit(schema.maximum)) bounds.push(`≤ ${schema.maximum}`);
  return bounds.length > 0 ? `${name} ${bounds.join(', ')}` : name;
}

export function renderBehaviorReference(behaviors: BehaviorRegistry): string {
  const lines = [
    '# Behavior reference',
    '',
    '> Generated by `npm run schemas` from the engine (`packages/sim/src/behaviors/`). Do not edit by hand: `npm run check` fails when this file is out of date.',
    '',
    'Behaviors are engine code. A theme picks one by its id and sets its parameters ([add a theme](../guides/add-a-theme.md)).',
  ];
  for (const section of SECTIONS) {
    lines.push('', `## ${section.title}`, '', `Used in ${section.file}.`);
    const list = behaviors.list(section.kind);
    if (list.length === 0) lines.push('', '*None yet.*');
    for (const behavior of list) {
      const schema = z.toJSONSchema(behavior.params, { io: 'input' }) as JsonSchema;
      lines.push('', `### \`${behavior.id}\``, '', behavior.description, '');
      lines.push('| Parameter | Type | Default | Meaning |', '|---|---|---|---|');
      for (const [name, param] of Object.entries(schema.properties ?? {})) {
        const required = schema.required?.includes(name) ?? false;
        const fallback = required ? 'required' : `\`${JSON.stringify(param.default ?? null)}\``;
        lines.push(`| \`${name}\` | ${typeOf(param)} | ${fallback} | ${param.description ?? ''} |`);
      }
    }
  }
  return `${lines.join('\n')}\n`;
}
